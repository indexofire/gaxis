#!/usr/bin/env bash
# Install / update gbrain into this project's environment.
#
# gbrain is not published as a package (the npm `gbrain` is an unrelated library),
# so we vendor the upstream repository and execute its TypeScript CLI with bun —
# both managed here rather than in the user's home directory.
#
#   source checkout   vendor/gbrain            (gitignored)
#   brain data        $GAXIS_GBRAIN_HOME       (default: ./.gbrain, gitignored)
#   PATH entry        .pixi/envs/default/bin/gbrain  (thin shim -> repo CLI)
#
# Usage:
#   pixi run gbrain-install                 # clone or update, install deps, link
#   GAXIS_GBRAIN_REF=v0.60.740.0 pixi run gbrain-install
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

src_dir="${GAXIS_GBRAIN_SRC:-$repo_root/vendor/gbrain}"
# upstream's default branch is `master`; keep it overridable for pinned refs
ref="${GAXIS_GBRAIN_REF:-HEAD}"
remote="${GAXIS_GBRAIN_REMOTE:-https://github.com/garrytan/gbrain.git}"
env_bin="$repo_root/.pixi/envs/default/bin"

# gbrain requires a recent bun; conda-forge lags behind, so install a pinned
# bun into vendor/bun when the environment's bun is too old.
required_bun="${GAXIS_BUN_VERSION:-1.4.4}"
bun_bin=""
if command -v bun >/dev/null; then
  have="$(bun --version 2>/dev/null || echo 0.0.0)"
  if [ "$(printf '%s\n%s\n' "$required_bun" "$have" | sort -V | head -1)" = "$required_bun" ]; then
    bun_bin="$(command -v bun)"
  fi
fi
if [ -z "$bun_bin" ]; then
  vendored="$repo_root/vendor/bun/bin/bun"
  if [ ! -x "$vendored" ]; then
    echo "==> bun >= $required_bun required; fetching pinned bun into vendor/bun"
    tmp="$(mktemp -d)"
    url="https://github.com/oven-sh/bun/releases/download/bun-v${required_bun}/bun-linux-x64.zip"
    python - "$url" "$tmp" <<'PY'
import sys, urllib.request, zipfile, pathlib
url, tmp = sys.argv[1], pathlib.Path(sys.argv[2])
archive = tmp / "bun.zip"
urllib.request.urlretrieve(url, archive)
with zipfile.ZipFile(archive) as zf:
    zf.extractall(tmp)
PY
    mkdir -p "$repo_root/vendor/bun/bin"
    cp -a "$tmp"/bun-linux-x64/. "$repo_root/vendor/bun/"
    # the release archive puts the binary at the top level, not in bin/
    if [ -f "$repo_root/vendor/bun/bun" ]; then
      mv "$repo_root/vendor/bun/bun" "$repo_root/vendor/bun/bin/bun"
    fi
    chmod +x "$repo_root/vendor/bun/bin/bun"
    rm -rf "$tmp"
  fi
  bun_bin="$vendored"
fi
echo "==> bun: $bun_bin ($("$bun_bin" --version))"

if [ -d "$src_dir/.git" ]; then
  echo "==> updating gbrain checkout ($src_dir @ $ref)"
  git -C "$src_dir" fetch --quiet --depth 1 origin "$ref"
  git -C "$src_dir" checkout --quiet FETCH_HEAD
else
  echo "==> cloning gbrain ($ref) into $src_dir"
  mkdir -p "$(dirname "$src_dir")"
  git clone --quiet --depth 1 --branch "$ref" "$remote" "$src_dir" 2>/dev/null \
    || git clone --quiet --depth 1 "$remote" "$src_dir"
fi

echo "==> bun install"
(cd "$src_dir" && "$bun_bin" install --silent)

version="$(cd "$src_dir" && "$bun_bin" run src/cli.ts --version 2>/dev/null | tail -1 || true)"

mkdir -p "$env_bin"
cat > "$env_bin/gbrain" <<SHIM
#!/usr/bin/env bash
# generated by scripts/install_gbrain.sh — do not edit.
# Delegates to scripts/gbrain.sh so bun selection and GBRAIN_HOME live in one place.
exec "$repo_root/scripts/gbrain.sh" "\$@"
SHIM
chmod +x "$env_bin/gbrain"

echo "==> gbrain ${version:-unknown} ready"
echo "    repo:  $src_dir"
echo "    shim:  $env_bin/gbrain"
echo "    next:  pixi run gbrain doctor"
echo "           pixi run gbrain --help"
